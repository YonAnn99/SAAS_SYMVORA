export function getMetodoPagoByVenta(metodoPago: string): string {
  switch (metodoPago) {
    case "EFECTIVO": return "01";
    case "TARJETA": return "04";
    case "TARJETA_TERMINAL": return "04";
    case "TRANSFERENCIA": return "03";
    case "CREDITO": return "01";
    default: return "01";
  }
}

export function getMetodoPagoCFDI(metodoPago: string): "PUE" | "PPD" {
  if (metodoPago === "CREDITO") return "PPD";
  return "PUE";
}

export function getDefaultClaveUnidad(unidadMedida: string): string {
  switch (unidadMedida) {
    case "PIEZA": return "H87";
    case "KG": return "KGM";
    case "GRAMO": return "GRM";
    case "LITRO": return "LTR";
    case "SERVICIO": return "E48";
    default: return "H87";
  }
}

export function formatCurrency(amount: number): string {
  return amount.toLocaleString("es-MX", {
    style: "currency",
    currency: "MXN",
  });
}
